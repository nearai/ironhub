#!/usr/bin/env node

import { promises as fs } from "node:fs"
import path from "node:path"
import process from "node:process"

const ROOT = process.cwd()
const TOOLS_DIR = path.join(ROOT, "tools")
const SKILLS_DIR = path.join(ROOT, "skills")
const TRACKING_FILE = path.join(ROOT, "tracking.md")
const CURATED_FILE = path.join(ROOT, "tracking-metadata.json")

const TOOL_HEADER =
  "| Name | Status | Version | Use Cases | Value Tags | Description | Limits | Author |"
const SKILL_HEADER =
  "| Name | Status | Version | Use Cases | Value Tags | Description | Trunk | Author |"
const DIVIDER = "|---|---|---|---|---|---|---|---|"

async function readJson(file) {
  return JSON.parse(await fs.readFile(file, "utf8"))
}

async function listDirs(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true })
  return entries
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .sort()
}

function stripQuotes(value) {
  const trimmed = value.trim()
  if (trimmed.length >= 2 && /^["'].*["']$/s.test(trimmed)) {
    return trimmed.slice(1, -1)
  }
  return trimmed
}

function frontmatter(source) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!match) return {}

  const lines = match[1].split(/\r?\n/)
  const parsed = {}
  let listKey = null
  let blockKey = null
  let blockIndent = 0

  for (const line of lines) {
    if (blockKey) {
      const indent = line.length - line.trimStart().length
      if (line.trim() !== "" && indent > blockIndent) {
        parsed[blockKey] = `${parsed[blockKey]} ${line.trim()}`.trim()
        continue
      }
      blockKey = null
    }

    const item = line.match(/^\s+-\s+(.*)$/)
    if (item && listKey) {
      parsed[listKey].push(stripQuotes(item[1]))
      continue
    }

    const pair = line.match(/^([A-Za-z0-9_]+):\s*(.*)$/)
    if (!pair) continue

    const [, key, rawValue] = pair
    listKey = null
    if (rawValue === "" ) {
      parsed[key] = []
      listKey = key
    } else if (rawValue === ">" || rawValue === "|" || rawValue === ">-" || rawValue === "|-") {
      parsed[key] = ""
      blockKey = key
      blockIndent = line.length - line.trimStart().length
    } else {
      parsed[key] = stripQuotes(rawValue)
    }
  }

  return parsed
}

function requiredTools(source) {
  const match = source.match(/^requires:\s*$([\s\S]*?)^---/m)
  if (!match) return []
  const tools = match[1].match(/^\s+tools:\s*$([\s\S]*?)(?=^\s{2}\w|\Z)/m)
  if (!tools) return []
  return [...tools[1].matchAll(/^\s+-\s+(.*)$/gm)].map(entry => stripQuotes(entry[1]))
}

function cell(value) {
  if (value === undefined || value === null || value === "") return ""
  const text = Array.isArray(value) ? value.join(", ") : String(value)
  return text.replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim()
}

function trunkCell(tools) {
  if (!tools.length) return "none"
  return tools.map(name => `\`${name}\``).join(", ")
}

async function collectTools(curated) {
  const rows = []
  for (const name of await listDirs(TOOLS_DIR)) {
    const manifest = path.join(TOOLS_DIR, name, "Cargo.toml")
    const capabilities = path.join(TOOLS_DIR, name, `${name}-tool.capabilities.json`)

    let version = ""
    try {
      const cargo = await fs.readFile(manifest, "utf8")
      version = cargo.match(/^version\s*=\s*"([^"]+)"/m)?.[1] ?? ""
    } catch {
      continue
    }

    let description = ""
    try {
      description = (await readJson(capabilities)).description ?? ""
    } catch {
      description = ""
    }

    const extra = curated.tools?.[name] ?? {}
    rows.push({
      name,
      version,
      description,
      useCases: extra.useCases ?? [],
      valueTags: extra.valueTags ?? [],
      limits: extra.limits ?? "",
      author: extra.author ?? "",
    })
  }
  return rows
}

async function collectSkills(curated) {
  const rows = []
  for (const name of await listDirs(SKILLS_DIR)) {
    const file = path.join(SKILLS_DIR, name, "SKILL.md")
    let source
    try {
      source = await fs.readFile(file, "utf8")
    } catch {
      continue
    }

    const meta = frontmatter(source)
    const extra = curated.skills?.[name] ?? {}
    rows.push({
      name,
      version: meta.version ?? "",
      description: meta.description ?? "",
      useCases: Array.isArray(meta.use_cases) ? meta.use_cases : [],
      valueTags: Array.isArray(meta.value_tags) ? meta.value_tags : [],
      trunk: requiredTools(source),
      author: extra.author ?? "",
    })
  }
  return rows
}

function render(tools, skills) {
  const today = new Date().toISOString().slice(0, 10)
  const lines = [
    "# Tracking",
    "",
    "Status of every tool and skill currently in this repository.",
    "",
    "This file is generated by `scripts/generate-tracking.mjs`. Do not edit it by hand.",
    "Derived fields come from each artifact's own metadata: tool descriptions and versions from",
    "`<name>-tool.capabilities.json` and `Cargo.toml`, skill descriptions, use cases, value tags",
    "and required tools from SKILL.md frontmatter. Curated fields that have no machine source,",
    "authorship plus tool use cases, value tags and limits, live in `tracking-metadata.json`.",
    "",
    `Last generated: ${today}`,
    "",
    "## Summary",
    "",
    `- ${tools.length} tools`,
    `- ${skills.length} skills`,
    "",
    "## Tools",
    "",
    TOOL_HEADER,
    DIVIDER,
  ]

  for (const tool of tools) {
    lines.push(
      `| \`${tool.name}\` | live | ${cell(tool.version)} | ${cell(tool.useCases)} | ` +
        `${cell(tool.valueTags)} | ${cell(tool.description)} | ${cell(tool.limits)} | ` +
        `${cell(tool.author)} |`,
    )
  }

  lines.push("", "## Skills", "", SKILL_HEADER, DIVIDER)

  for (const skill of skills) {
    lines.push(
      `| \`${skill.name}\` | live | ${cell(skill.version)} | ${cell(skill.useCases)} | ` +
        `${cell(skill.valueTags)} | ${cell(skill.description)} | ${trunkCell(skill.trunk)} | ` +
        `${cell(skill.author)} |`,
    )
  }

  const incomplete = skills.filter(skill => !skill.useCases.length || !skill.valueTags.length)
  if (incomplete.length) {
    lines.push(
      "",
      "## Skills missing catalogue metadata",
      "",
      `${incomplete.length} of ${skills.length} skills do not declare \`use_cases\` or`,
      "`value_tags` in their SKILL.md frontmatter, so those columns are blank above. The data",
      "belongs in each SKILL.md, not here. This list is regenerated, so entries disappear as the",
      "frontmatter is filled in.",
      "",
      "| Skill | Missing |",
      "|---|---|",
    )
    for (const skill of incomplete) {
      const missing = []
      if (!skill.useCases.length) missing.push("`use_cases`")
      if (!skill.valueTags.length) missing.push("`value_tags`")
      lines.push(`| \`${skill.name}\` | ${missing.join(", ")} |`)
    }
  }

  lines.push(
    "",
    "## Open work",
    "",
    "Proposed and in-progress tools and skills are tracked as GitHub issues. Filter by label:",
    "",
    "- `type:tool`, `type:skill`, `type:bug`",
    "- `status:proposed`, `status:in-progress`, `status:blocked`",
    "- `trunk:<tool-name>` (links a proposed skill to its required trunk)",
    "",
    "## Status definitions",
    "",
    "- **proposed**: issue filed, no code yet, no claimed author",
    "- **in-progress**: branch exists, work underway",
    "- **live**: merged to main, CI green, included in this table",
    "- **blocked**: dependency or external decision required, named in the issue",
    "- **deprecated**: superseded by a different integration or removed; documented in the relevant PR",
    "",
  )

  return lines.join("\n")
}

function reportGaps(tools, skills) {
  const gaps = []
  for (const tool of tools) {
    if (!tool.author) gaps.push(`tools/${tool.name}: no author in tracking-metadata.json`)
    if (!tool.description) gaps.push(`tools/${tool.name}: no description in capabilities.json`)
  }
  for (const skill of skills) {
    if (!skill.author) gaps.push(`skills/${skill.name}: no author in tracking-metadata.json`)
    if (!skill.description) gaps.push(`skills/${skill.name}: no description in SKILL.md`)
    if (!skill.useCases.length) gaps.push(`skills/${skill.name}: no use_cases in SKILL.md`)
    if (!skill.valueTags.length) gaps.push(`skills/${skill.name}: no value_tags in SKILL.md`)
  }
  return gaps
}

async function main() {
  const check = process.argv.includes("--check")
  const quiet = process.argv.includes("--quiet")

  let curated = { tools: {}, skills: {} }
  try {
    curated = await readJson(CURATED_FILE)
  } catch {
    curated = { tools: {}, skills: {} }
  }

  const tools = await collectTools(curated)
  const skills = await collectSkills(curated)
  const rendered = render(tools, skills)

  if (check) {
    let current = ""
    try {
      current = await fs.readFile(TRACKING_FILE, "utf8")
    } catch {
      current = ""
    }
    const normalise = text => text.replace(/^Last generated: .*$/m, "").trim()
    if (normalise(current) !== normalise(rendered)) {
      console.error(
        "tracking.md is out of date. Run `node scripts/generate-tracking.mjs` and commit the result.",
      )
      process.exit(1)
    }
    console.log(`tracking.md is current: ${tools.length} tools, ${skills.length} skills.`)
    return
  }

  await fs.writeFile(TRACKING_FILE, rendered, "utf8")
  console.log(`wrote tracking.md: ${tools.length} tools, ${skills.length} skills`)

  if (!quiet) {
    const gaps = reportGaps(tools, skills)
    if (gaps.length) {
      console.log(`\n${gaps.length} metadata gap(s):`)
      for (const gap of gaps) console.log(`  ${gap}`)
    }
  }
}

main().catch(error => {
  console.error(error)
  process.exit(1)
})
